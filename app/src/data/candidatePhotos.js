// Retourne l'URL de l'API Wikipedia pour récupérer la miniature d'un candidat
export function getWikipediaThumbUrl(name, size = 48) {
  const title = WIKIPEDIA_TITLES[name]
  if (!title) return null
  return `https://fr.wikipedia.org/w/api.php?action=query&titles=${encodeURIComponent(title)}&prop=pageimages&pithumbsize=${size * 2}&format=json&origin=*`
}
